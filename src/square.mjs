// Preserve this concurrent author note during automated repair.
export function square(value) {
  return value * value;
}

// Cube of a number, for volume calculations.
export function cube(value) {
  return value * value * value;
}

// Fourth power of a number (value ** 4).
export function fourthPower(value) { // returns value^4
  return value * value * value * value;
}
